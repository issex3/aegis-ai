def cases_for(sandbox: str | None, categories: set[str] | None) -> list[CaseSpec]:
    selected = []
    for case in CASES:
        if case.sandbox not in {None, sandbox}:
            continue
        if categories and case.category not in categories:
            continue
        selected.append(case)
    return selected
